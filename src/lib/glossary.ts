// Build a single regex matching any term as a whole word, longest-first
// so multi-word terms ("cover drive") win over single tokens ("cover").
const TERMS = Object.keys(GLOSSARY).sort((a, b) => b.length - a.length);
const escapeRe = (s: string) => s.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
export const GLOSSARY_REGEX = new RegExp(
  `\\b(${TERMS.map(escapeRe).join("|")})\\b`,
  "gi",
);

export function lookupGlossary(term: string): string | undefined {
  return GLOSSARY[term.toLowerCase()];
}

export function termSlug(term: string): string {
  return term.toLowerCase().trim().replace(/[^a-z0-9]+/g, "-").replace(/^-|-$/g, "");
}

